"""Emit app_vectors.tsv: the merge layer's expected values computed by the Sim Configurator's OWN code, not by
PenguinBox's (a second implementation, written by another session): its profile/signal.py Range (normalise,
denormalise), its ui/axis_response.py AxisResponseModel.evaluate (descriptor range, invert, deadzone, window, the
target's raw value, continuous) and its profile/relative.py Integrator (O-23).

Run with the app's own interpreter (it needs PySide6 for the ui module):
  SIMCFG=<a sim-configurator checkout>
  "$SIMCFG/.venv/bin/python3" tests/xbox/simmerge/gen_app_vectors.py "$SIMCFG" > tests/xbox/simmerge/app_vectors.tsv
The header line records the app's commit. Never edit the output by hand.
"""
import os
import subprocess
import sys

app = os.path.abspath(sys.argv[1])
sys.path.insert(0, os.path.join(app, "src"))
os.environ.setdefault("QT_QPA_PLATFORM", "offscreen")

from sim_configurator.profile.signal import Range  # noqa: E402
from sim_configurator.profile.relative import Integrator  # noqa: E402
from sim_configurator.ui.axis_response import AxisResponseModel  # noqa: E402

sha = subprocess.run(["git", "-C", app, "rev-parse", "HEAD"], capture_output=True, text=True).stdout.strip()
print("# generated by gen_app_vectors.py from sim-configurator %s; do not edit" % sha)
print("# norm  min rest max v -> c | denorm min rest max c -> v | eval smin srest smax tmin trest tmax invert "
      "deadzone wlo whi raw -> output target_raw | integ tmin trest tmax N invert motions(,) -> position")


def f(x):
    return repr(float(x))


RANGES = [(-32768, 0, 32767), (0, 32768, 65535), (0, 0, 255), (0, 0, 65535), (65535, 65535, 0), (0, 1023, 1023),
          (-100, 20, 50), (0, 128, 255)]
for r in RANGES:
    R = Range(*r)
    lo, hi = min(r[0], r[2]), max(r[0], r[2])
    for v in (r[0], r[2], r[1], (r[0] + r[1]) / 2, (r[1] + r[2]) / 2, lo + 1, hi - 1, (r[0] + 3 * r[2]) / 4):
        # inside the range only: the app's normalise does not clamp, the merge layer's does (eval rows cover clamping)
        print("norm\t%s\t%s\t%s\t%s\t%s" % (f(r[0]), f(r[1]), f(r[2]), f(v), f(R.normalise(v))))
    cs = (-1, -0.5, -0.25, 0, 0.25, 0.5, 0.75, 1) if R.is_bipolar() else (0, 0.1, 0.25, 0.5, 0.75, 1)
    for c in cs:
        print("denorm\t%s\t%s\t%s\t%s\t%s" % (f(r[0]), f(r[1]), f(r[2]), f(c), f(R.denormalise(c))))

PAIRS = [((-32768, 0, 32767), (-32768, 0, 32767)), ((-32768, 0, 32767), (0, 32768, 65535)),
         ((0, 0, 1023), (0, 0, 65535)), ((0, 0, 255), (0, 0, 65535)), ((65535, 65535, 0), (0, 0, 65535)),
         ((-100, 20, 50), (-32768, 0, 32767))]
SHAPES = [(False, 0.0, (0.0, 1.0)), (True, 0.0, (0.0, 1.0)), (False, 0.1, (0.0, 1.0)), (False, 0.0, (0.1, 0.9)),
          (True, 0.2, (0.05, 0.8)), (False, 0.3, (0.1, 0.5))]
for s, t in PAIRS:
    S, T = Range(*s), Range(*t)
    for inv, dz, win in SHAPES:
        lo, hi = min(s[0], s[2]), max(s[0], s[2])
        for raw in sorted({lo, hi, s[1], lo + (hi - lo) * 0.07, lo + (hi - lo) * 0.33, lo + (hi - lo) * 0.5,
                           lo + (hi - lo) * 0.61, lo + (hi - lo) * 0.95, lo - 10, hi + 10}):
            m = AxisResponseModel(source=S, target=T, raw=raw, invert=inv, deadzone=dz, window=win)
            r = m.evaluate()
            if r.target_raw is None:
                continue
            print("eval\t%s\t%s\t%s\t%s\t%s\t%s\t%d\t%s\t%s\t%s\t%s\t%s\t%s" % (
                f(s[0]), f(s[1]), f(s[2]), f(t[0]), f(t[1]), f(t[2]), int(inv), f(dz), f(win[0]), f(win[1]),
                f(raw), f(r.output), f(r.target_raw)))

RUNS = [((0, 32768, 65535), 2000, False, [100]), ((0, 32768, 65535), 2000, False, [2000, -1]),
        ((0, 32768, 65535), 2000, True, [100, 250, -30]), ((-32768, 0, 32767), 500, False, [-600, 3, 7]),
        ((0, 0, 65535), 1000, False, [-50, 400, 400, 400, -2]), ((0, 32768, 65535), 2000, False, [0.5, 0.25, -0.125])]
for t, n, inv, motions in RUNS:
    I = Integrator(Range(*t), n, inv)
    p = I.run(motions)
    print("integ\t%s\t%s\t%s\t%s\t%d\t%s\t%s" % (f(t[0]), f(t[1]), f(t[2]), f(n), int(inv),
                                                ",".join(f(x) for x in motions), f(p)))
